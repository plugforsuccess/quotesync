-- Rate Check: allow the rate-check audit events on audit_log.
-- audit_log.event_type is allowlisted; without these the rate-check /
-- rate-check-outcome / rate-check-cleanup audit inserts are rejected.
-- Existing values are carried over unchanged.
alter table public.audit_log drop constraint if exists audit_log_event_type_check;
alter table public.audit_log add constraint audit_log_event_type_check
  check (event_type = any (array[
    'LEAD_CREATED', 'ROUTED', 'NOTIFIED', 'ROUTING_FALLBACK', 'STATUS_CHANGED', 'ASSIGNED',
    'LEAD_STATUS_UPDATED', 'LEAD_DISPOSED', 'SMS_SENT', 'SMS_INBOUND', 'SMS_DRIP_SENT',
    'SMS_DRIP_FAILED', 'SMS_MANUAL_SENT', 'CALL_INITIATED', 'CALL_CONNECTED', 'CALL_MISSED',
    'CANOPY_WEBHOOK_RECEIVED', 'ENRICHMENT_ORPHAN_PULL', 'ENRICHMENT_STARTED',
    'ENRICHMENT_SUCCEEDED', 'ENRICHMENT_FAILED', 'AGENT_AVAILABILITY_ON',
    'AGENT_AVAILABILITY_OFF', 'AGENT_AVAILABILITY_AUTO_RESET', 'AGENT_TRANSFER_PHONE_SET',
    'BLAND_OUTBOUND_INITIATED', 'BLAND_OUTBOUND_FAILED', 'BLAND_OUTBOUND_TRANSFERRED',
    'BLAND_TRANSFER_MISSED', 'LEAD_QUALIFIED_BLAND', 'LEAD_DISQUALIFIED_BLAND',
    'BLAND_INBOUND_TRANSFERRED', 'BLAND_CALLBACK_REQUESTED', 'BLAND_WEBHOOK_ERROR',
    'CANOPY_LINK_SENT_BLAND', 'BLAND_INBOUND_EXISTING_CUSTOMER',
    'CANOPY_SEND_DEFERRED_NO_TRANSCRIPT', 'LEAD_ACTIVATED', 'BLAND_RETRY_SCHEDULED',
    'BLAND_HANDOFF_TO_DRIP', 'CANOPY_SEND_RETRY_SUCCESS', 'BLAND_INBOUND_PARTIAL_CAPTURE',
    'REFERRAL_REFERRER_CREATED', 'REFERRAL_ENTRY_ADDED', 'REFERRAL_ENTRY_REMOVED',
    'REFERRAL_PAYOUT_UPDATED',
    -- Rate Check
    'RATE_CHECK_RECEIVED', 'RATE_CHECK_EXTRACTED', 'RATE_CHECK_FAILED',
    'RATE_CHECK_QUOTED', 'RATE_CHECK_IMAGES_PURGED'
  ]::text[]));
